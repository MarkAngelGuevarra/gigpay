import React, { createContext, useState, useContext, useEffect, useMemo } from 'react';
import { supabase } from '../lib/supabase';
import { useAuth } from './AuthContext';
import { useToast } from './ToastContext';
import { requestWalletSignature, submitFundTask, submitApproveTask, getFundTaskOutcome, GIGPAY_ESCROW_CONTRACT_ID, isValidStellarAddress } from '../lib/stellar';
import { isNonEvidenceHash, buildCompletedTaskLedgerRow, labelLedgerRecord, dedupeLedgerByTxHash } from '../lib/ledgerIntegrity';
import onchainEscrows from '../data/onchainEscrows.json';
import { mergeTaskRecords, isDisputeActive } from '../lib/taskLifecycle';

const TaskContext = createContext();

export const useTasks = () => useContext(TaskContext);

// Resilient shared cache keys per Armielyn Obinguar's SOW specification
const GIGPAY_SHARED_TASKS_KEY = 'gigpay_shared_tasks';
const GIGPAY_LEGACY_CACHE_KEY = 'gigpay_tasks_cache_v2';
const GIGPAY_LEDGER_CACHE_KEY = 'gigpay_verification_ledger_v1';

// Strict G-address check matching the tasks_*_wallet_stellar DB constraints (demo keys fail it).
const isRealStellarAddress = (val) => typeof val === 'string' && /^G[A-Z2-7]{55}$/.test(val);

const isUuid = (val) => typeof val === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(val);

// Sample tasks are no longer seeded. The old seed injected a 'Create a website, 100 XLM, Completed' task
// (and re-inserted it if removed) into every browser, so every new tester saw a payout that never happened.
// Cached copies of those seeds are filtered out here so existing testers stop seeing them too.
const RETIRED_SEED_TASK_IDS = new Set(['task-website-100', 'task-mock-1', 'task-mock-2']);

const getLocalTasks = () => {
  try {
    const raw = localStorage.getItem(GIGPAY_SHARED_TASKS_KEY) || localStorage.getItem(GIGPAY_LEGACY_CACHE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((t) => t && !RETIRED_SEED_TASK_IDS.has(t.id));
  } catch (err) {
    console.warn("[GigPay Sync] Local cache read warning:", err);
    return [];
  }
};

const setLocalTasks = (tasksList) => {
  try {
    const jsonStr = JSON.stringify(tasksList);
    localStorage.setItem(GIGPAY_SHARED_TASKS_KEY, jsonStr);
    localStorage.setItem(GIGPAY_LEGACY_CACHE_KEY, jsonStr);
  } catch (err) {
    console.warn("[GigPay Sync] Local cache write warning:", err);
  }
};

// Task UUID -> on-chain escrow overrides. Intentionally empty.
// The previous entries linked Supabase tasks created in July 2026 to escrows #13–#31, which were
// generated by a script on Nov 3, 2026 (or funded by team wallets) at 1/10 of the task amounts. None
// of those links can be verified, so they are not shown as evidence. A task now carries its own
// on_chain_task_id / client_wallet / freelancer_wallet only when it is funded on-chain through the app.
const VERIFIED_TASK_ONCHAIN_MAP = {};

const isUnverifiedDemoHash = isNonEvidenceHash;

const sanitizeTaskRecord = (t) => {
  if (!t) return t;
  const mapped = VERIFIED_TASK_ONCHAIN_MAP[t.id];
  if (mapped) {
    const cleanHash = mapped.releaseHash || mapped.txHash;
    return {
      ...t,
      contract_id: GIGPAY_ESCROW_CONTRACT_ID,
      on_chain_task_id: mapped.onChainTaskId,
      client_wallet: mapped.clientWallet,
      freelancer_wallet: mapped.freelancerWallet,
      tx_hash: mapped.txHash,
      release_tx_hash: cleanHash,
      explorer_url: `https://stellar.expert/explorer/testnet/tx/${cleanHash}`
    };
  }
  // Demo-funded tasks keep their own placeholder hash and lose the explorer link. They must not
  // borrow another task's real transaction: that would present demo activity as on-chain evidence.
  const fundIsEvidence = !isNonEvidenceHash(t.tx_hash);
  const releaseIsEvidence = !t.release_tx_hash || !isNonEvidenceHash(t.release_tx_hash);
  if (!fundIsEvidence || !releaseIsEvidence) {
    return { ...t, is_simulated: true, explorer_url: null };
  }
  return t;
};

// Public verification ledger rows, generated from the chain by scripts/index_escrows.mjs (src/data/onchainEscrows.json).
// One row per escrow; each is labeled outside user vs team/scripted wallet by labelLedgerRecord. No names are attached.
// Regenerate with: node scripts/index_escrows.mjs --write
const INITIAL_VERIFICATION_LEDGER = onchainEscrows.escrows.map((e) => ({
  id: `onchain-${e.onChainTaskId}`,
  taskId: `Escrow #${e.onChainTaskId} (${e.walletKind})`,
  method: e.released ? "fund_task & approve_task" : "fund_task",
  amount: `${e.amount} XLM`,
  contractId: GIGPAY_ESCROW_CONTRACT_ID,
  clientWallet: e.clientWallet,
  freelancerWallet: e.freelancerWallet,
  txHash: e.releaseTxHash || e.fundTxHash,
  fundTxHash: e.fundTxHash,
  releaseHash: e.releaseTxHash,
  status: e.released ? "Completed & Released" : "Escrow Locked (not released)",
  timestamp: (e.releasedAt || e.fundedAt).replace("T", " ").replace("Z", " UTC"),
  explorerUrl: `https://stellar.expert/explorer/testnet/tx/${e.releaseTxHash || e.fundTxHash}`
}));

export const TaskProvider = ({ children }) => {
  const { user, publicKey, ensureDbRole } = useAuth();
  const { addToast } = useToast();

  // 1. Zero-Flash Hydration: initialize immediately from local cache so UI renders in 0ms
  const [tasks, setTasks] = useState(() => getLocalTasks().map(sanitizeTaskRecord));
  const [isLoading, setIsLoading] = useState(false);

  // Raw stored ledger records (filtering out any unverified demo/simulated hashes)
  const [storedLedgerRecords, setStoredLedgerRecords] = useState(() => {
    try {
      const stored = localStorage.getItem(GIGPAY_LEDGER_CACHE_KEY);
      const parsed = stored ? JSON.parse(stored) : [];
      return Array.isArray(parsed) ? parsed.filter(r => !isUnverifiedDemoHash(r?.txHash)) : [];
    } catch {
      return [];
    }
  });

  // BroadcastChannel instance for real-time inter-tab communications
  const broadcastChannel = useMemo(() => {
    try {
      if (typeof window !== 'undefined' && 'BroadcastChannel' in window) {
        return new BroadcastChannel('gigpay_sync_channel');
      }
    } catch (e) {
      console.warn("BroadcastChannel not supported, falling back to storage listener", e);
    }
    return null;
  }, []);

  // Lifecycle Monotonic Merge: higher lifecycle status (Completed > In Progress > Available) is permanent
  const mergeTaskLists = (currentList, incomingList) => {
    const taskMap = new Map();

    (incomingList || []).filter(t => t && !RETIRED_SEED_TASK_IDS.has(t.id)).forEach(rawT => {
      const t = sanitizeTaskRecord(rawT);
      const key = t.id || t.title;
      taskMap.set(key, t);
    });

    (currentList || []).filter(t => t && !RETIRED_SEED_TASK_IDS.has(t.id)).forEach(rawT => {
      const t = sanitizeTaskRecord(rawT);
      const key = t.id || t.title;
      if (taskMap.has(key)) {
        const incoming = taskMap.get(key);
        // Rank for stages (never demote a completed milestone); dispute timestamps for Disputed <-> In Progress.
        const winner = mergeTaskRecords(t, incoming);
        // Escrow identity is write-once: a side that lacks it (e.g. an older DB row) must not erase it.
        for (const field of ['on_chain_task_id', 'client_wallet', 'freelancer_wallet']) {
          winner[field] = winner[field] ?? t[field] ?? incoming[field] ?? null;
        }
        taskMap.set(key, sanitizeTaskRecord(winner));
      } else {
        taskMap.set(key, t);
      }
    });

    return Array.from(taskMap.values());
  };

  // Helper to update state and atomic localStorage cache simultaneously
  const updateTasksAndCache = (updater) => {
    setTasks((prev) => {
      const nextRaw = typeof updater === 'function' ? updater(prev) : updater;
      const next = mergeTaskLists(prev, nextRaw);
      setLocalTasks(next);
      if (broadcastChannel) {
        try {
          broadcastChannel.postMessage({ type: 'SYNC_TASKS', tasks: next });
        } catch (e) {
          console.warn("BroadcastChannel postMessage error:", e);
        }
      }
      return next;
    });
  };

  // Puts one task back exactly as it was, bypassing the merge. The merge never lowers a status (so a stale
  // copy can't undo progress), which also meant a failed release or claim could never be rolled back:
  // the task stayed "Completed" on screen, counted as released, and Release could not be retried.
  const restoreTask = (snapshot) => {
    if (!snapshot?.id) return;
    setTasks((prev) => {
      const next = prev.map((t) => (t.id === snapshot.id ? snapshot : t));
      setLocalTasks(next);
      if (broadcastChannel) {
        try {
          broadcastChannel.postMessage({ type: 'RESTORE_TASK', task: snapshot });
        } catch (e) {
          console.warn("BroadcastChannel postMessage error:", e);
        }
      }
      return next;
    });
  };

  // supabase-js returns errors instead of throwing; every write must check them, or the user is told an
  // action worked when the database (RLS / guard trigger) rejected it.
  const writeTask = async (id, fields) => {
    if (!isUuid(id)) return null;
    try {
      const { error } = await supabase.from('tasks').update(fields).eq('id', id);
      return error || null;
    } catch (dbErr) {
      return dbErr;
    }
  };

  const addLedgerRecord = (record) => {
    setStoredLedgerRecords((prev) => {
      const updated = [record, ...prev.filter(r => r.id !== record.id && r.txHash !== record.txHash)];
      try {
        localStorage.setItem(GIGPAY_LEDGER_CACHE_KEY, JSON.stringify(updated));
      } catch (e) {
        console.warn("Failed to persist ledger record:", e);
      }
      return updated;
    });
  };

  // 2. Real-Time Cross-Tab / Multi-Window Synchronization (Storage Events + BroadcastChannel)
  useEffect(() => {
    const handleStorageChange = (e) => {
      if ((e.key === GIGPAY_SHARED_TASKS_KEY || e.key === GIGPAY_LEGACY_CACHE_KEY) && e.newValue) {
        try {
          const syncedTasks = JSON.parse(e.newValue);
          if (Array.isArray(syncedTasks)) {
            setTasks((prev) => mergeTaskLists(prev, syncedTasks));
          }
        } catch (err) {
          console.warn("[GigPay Sync] Cross-tab storage parse exception:", err);
        }
      }
    };

    window.addEventListener('storage', handleStorageChange);

    if (broadcastChannel) {
      broadcastChannel.onmessage = (event) => {
        if (event.data?.type === 'SYNC_TASKS' && Array.isArray(event.data.tasks)) {
          setTasks((prev) => mergeTaskLists(prev, event.data.tasks));
        }
        if (event.data?.type === 'RESTORE_TASK' && event.data.task?.id) {
          setTasks((prev) => prev.map((t) => (t.id === event.data.task.id ? event.data.task : t)));
        }
      };
    }

    return () => {
      window.removeEventListener('storage', handleStorageChange);
      if (broadcastChannel) {
        broadcastChannel.onmessage = null;
      }
    };
  }, [broadcastChannel]);

  // 2b. Resolve escrows whose funding was sent but not confirmed while the client waited ("Confirming").
  // The chain is the source of truth: SUCCESS fills in the escrow ID and opens the task; FAILED, or a
  // transaction still unknown after 5 minutes (Soroban transactions expire long before that), marks it Failed.
  const confirmingKey = tasks
    .filter((t) => t.status === 'Confirming' && t.client_id === user?.id && /^[0-9a-f]{64}$/.test(t.tx_hash || ''))
    .map((t) => t.id)
    .join(',');
  useEffect(() => {
    if (!confirmingKey) return undefined;
    let cancelled = false;
    const check = async () => {
      for (const t of tasks.filter((x) => confirmingKey.split(',').includes(x.id))) {
        try {
          const outcome = await getFundTaskOutcome(t.tx_hash);
          if (cancelled) return;
          const ageMs = Date.now() - Date.parse(t.created_at || 0);
          let fields = null;
          if (outcome.status === 'SUCCESS' && outcome.onChainTaskId) {
            fields = { status: 'Available', on_chain_task_id: outcome.onChainTaskId, is_simulated: false };
          } else if (outcome.status === 'FAILED' || (outcome.status === 'NOT_FOUND' && ageMs > 5 * 60 * 1000)) {
            fields = { status: 'Failed' };
          }
          if (!fields) continue;
          const { is_simulated: _local, ...dbFields } = fields;
          await writeTask(t.id, dbFields);
          restoreTask({ ...t, ...fields, explorer_url: fields.status === 'Available' ? `https://stellar.expert/explorer/testnet/tx/${t.tx_hash}` : t.explorer_url });
          addToast(fields.status === 'Available'
            ? `"${t.title}" is confirmed on Stellar and open for your freelancer.`
            : `"${t.title}" didn't go through on Stellar, so no money was locked. You can create it again.`,
          fields.status === 'Available' ? 'success' : 'warning');
        } catch (err) {
          console.warn('[GigPay] Confirming-task check notice:', err?.message || err);
        }
      }
    };
    check();
    const timer = setInterval(check, 15000);
    return () => { cancelled = true; clearInterval(timer); };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [confirmingKey]);

  // 3. Database Fetch & Supabase Realtime Pipeline
  useEffect(() => {
    const fetchTasks = async () => {
      try {
        const { data, error } = await supabase
          .from('tasks')
          .select('*')
          .order('created_at', { ascending: false });
        
        if (!error && data && data.length > 0) {
          updateTasksAndCache(data);
        }
      } catch (err) {
        console.warn("[GigPay Sync] Fetch tasks notice, preserving local state:", err);
      }
    };

    fetchTasks();

    // Supabase Realtime Webhook Channel
    const channel = supabase
      .channel('schema-db-changes')
      .on(
        'postgres_changes',
        { event: '*', schema: 'public', table: 'tasks' },
        (payload) => {
          if (payload.eventType === 'INSERT') {
            updateTasksAndCache((prev) => [payload.new, ...prev.filter(t => t.id !== payload.new.id)]);
          } else if (payload.eventType === 'UPDATE') {
            updateTasksAndCache((prev) => prev.map((t) => t.id === payload.new.id ? { ...t, ...payload.new } : t));
          } else if (payload.eventType === 'DELETE') {
            updateTasksAndCache((prev) => prev.filter((t) => t.id !== payload.old.id));
          }
        }
      )
      .subscribe();

    return () => {
      supabase.removeChannel(channel);
    };
  }, [user]);

  // 4. Add Task with Optimistic Local Cache & Background DB Sync
  const addTask = async (task) => {
    const activeKey = publicKey || 'GBDEMO_GIGPAY_WALLET_FALLBACK_ACTIVE_V9XQ3P';
    // The contract fixes the payout recipient at fund time, so the freelancer's own wallet must be
    // passed here. A missing address is never replaced by a team wallet: submitFundTask requires a real,
    // activated payout address (only the offline demo, which locks nothing on-chain, uses the demo key).
    const requestedFreelancer = typeof task.freelancer_wallet === 'string' ? task.freelancer_wallet.trim() : '';
    if (requestedFreelancer && !isValidStellarAddress(requestedFreelancer)) {
      throw new Error("The freelancer wallet address isn't valid. It should start with G and be 56 characters long.");
    }

    // Confirm the Client role in the database BEFORE locking money: otherwise RLS rejects the task row after
    // the escrow is already funded on-chain, stranding it where the freelancer can never see it.
    if (typeof ensureDbRole === 'function' && !(await ensureDbRole('client'))) {
      throw new Error("GigPay couldn't confirm your Client role, so no money was locked. Sign out, sign back in, then try again.");
    }

    try {
      const fundResult = await submitFundTask({
        clientAddress: activeKey,
        freelancerAddress: requestedFreelancer || undefined,
        amount: task.amount
      });
      const recipientWallet = fundResult?.freelancerAddress || requestedFreelancer || null;

      const txHash = fundResult?.hash || ('sim-tx-' + Date.now());
      // Sent but not confirmed yet: keep the task as "Confirming" (with its hash) and resolve it from the
      // chain later, instead of recording an escrow that may not exist or inviting a second funding.
      const isPending = !!fundResult?.pending;
      const isEvidence = !isPending && !fundResult?.isDemo && !isNonEvidenceHash(txHash);
      const explorerUrl = isEvidence ? (fundResult?.explorerUrl || `https://stellar.expert/explorer/testnet/tx/${txHash}`) : null;
      const resolvedClientWallet = fundResult?.clientAddress || (typeof activeKey === 'string' ? activeKey : 'GBDEMO_GIGPAY_WALLET_FALLBACK_ACTIVE_V9XQ3P');

      const generatedId = (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') ? crypto.randomUUID() : ('task-' + Date.now());
      const newTask = {
        id: generatedId,
        title: task.title,
        amount: String(task.amount),
        status: isPending ? 'Confirming' : 'Available',
        client_id: user?.id || 'demo-client-uuid-001',
        client_wallet: resolvedClientWallet,
        freelancer_wallet: recipientWallet,
        on_chain_task_id: fundResult?.onChainTaskId || null,
        contract_id: GIGPAY_ESCROW_CONTRACT_ID,
        tx_hash: txHash,
        explorer_url: explorerUrl,
        is_simulated: !isEvidence,
        created_at: new Date().toISOString()
      };

      updateTasksAndCache((prev) => [newTask, ...prev]);

      // Only confirmed on-chain transactions go into the public verification ledger.
      if (isEvidence) {
        addLedgerRecord(labelLedgerRecord({
          id: 'tx-fund-' + Date.now(),
          taskId: newTask.title,
          method: 'fund_task',
          amount: `${task.amount} XLM`,
          contractId: GIGPAY_ESCROW_CONTRACT_ID,
          clientWallet: resolvedClientWallet,
          freelancerWallet: recipientWallet,
          txHash: txHash,
          status: 'Escrow Locked',
          timestamp: new Date().toISOString().replace('T', ' ').substring(0, 19) + ' UTC',
          explorerUrl: explorerUrl
        }));
      }

      if (isUuid(user?.id)) {
        try {
          const { error: insertError } = await supabase
            .from('tasks')
            .insert([{
              title: task.title,
              amount: task.amount,
              status: newTask.status,
              id: isUuid(generatedId) ? generatedId : undefined,
              client_id: user.id,
              tx_hash: txHash,
              explorer_url: explorerUrl,
              contract_id: GIGPAY_ESCROW_CONTRACT_ID,
              // Escrow identity, so a release from any device targets this task's own escrow.
              // Placeholder/demo values are sent as null (the DB rejects non-G-address wallets).
              on_chain_task_id: newTask.on_chain_task_id,
              client_wallet: (isEvidence || isPending) && isRealStellarAddress(resolvedClientWallet) ? resolvedClientWallet : null,
              freelancer_wallet: (isEvidence || isPending) && isRealStellarAddress(recipientWallet) ? recipientWallet : null
            }]);
          // supabase-js reports errors in the result instead of throwing; surface them for debugging.
          if (insertError) {
            console.warn("Supabase insert notice (using local synced state):", insertError);
            // The escrow may already be locked on-chain, so never suggest funding it again.
            addToast(`Your payment is locked on Stellar, but GigPay couldn't share this task with your freelancer. Please don't lock funds again: send the GigPay team this transaction: ${txHash.slice(0, 12)}…`, "warning");
          }
        } catch (dbErr) {
          console.warn("Supabase insert notice (using local synced state):", dbErr);
        }
      }

      if (fundResult?.payoutWarning) {
        addToast(fundResult.payoutWarning, "warning");
      }
      if (isPending) {
        addToast("The network is slow, so your escrow is still confirming. Please don't lock funds again; GigPay will update this task by itself.", "warning");
      } else if (fundResult?.explorerUrl && !fundResult?.isDemo) {
        addToast(`Escrow funded on Testnet! Tx: ${txHash.slice(0, 10)}...`, "success");
      }
    } catch (err) {
      console.error("Failed to add task:", err);
      throw err;
    }
  };

  // 5. Submit Proof of Work
  const submitProofOfWork = async (id, { githubPrUrl, docUrl, loomUrl, notes }) => {
    const task = tasks.find(t => t.id === id);
    if (!task) throw new Error("Task not found");

    const proofData = {
      status: 'Under Review',
      github_pr_url: githubPrUrl || null,
      doc_url: docUrl || null,
      loom_url: loomUrl || null,
      submission_notes: notes || '',
      submitted_at: new Date().toISOString(),
      proof_attached: true
    };

    updateTasksAndCache((prev) => prev.map(t => t.id === id ? { ...t, ...proofData } : t));

    const proofError = await writeTask(id, proofData);
    if (proofError) {
      console.warn("Supabase proof-of-work update notice:", proofError);
      restoreTask(task);
      throw new Error("GigPay couldn't save your proof of work, so your client can't see it yet. Check you're signed in as the freelancer on this task, then try again.");
    }

    addToast("Proof of work submitted! The client can now review your deliverables.", "success");
  };

  // 6. Raise Dispute Freeze Action
  const raiseDispute = async (id, reason = "Deliverables do not match agreed specifications.") => {
    const task = tasks.find(t => t.id === id);
    if (!task) throw new Error("Task not found");

    const disputeData = {
      status: 'Disputed',
      dispute_reason: reason,
      disputed_at: new Date().toISOString(),
      disputed_by: user?.id || 'client-uuid'
    };

    updateTasksAndCache((prev) => prev.map(t => t.id === id ? { ...t, ...disputeData } : t));

    const disputeError = await writeTask(id, disputeData);
    if (disputeError) {
      console.warn("Supabase dispute notice:", disputeError);
      restoreTask(task);
      throw new Error("GigPay couldn't save the dispute, so nothing was frozen. Only the client who funded this task can dispute it; try again.");
    }

    addToast("Task has been marked as Disputed. Escrow release is frozen.", "warning");
  };

  // 7. Resolve Dispute Action
  const resolveDispute = async (id) => {
    const task = tasks.find(t => t.id === id);
    if (!task) return;

    const resolvedData = {
      status: 'In Progress',
      dispute_resolved_at: new Date().toISOString()
    };

    updateTasksAndCache((prev) => prev.map(t => t.id === id ? { ...t, ...resolvedData } : t));

    const resolveError = await writeTask(id, resolvedData);
    if (resolveError) {
      console.warn("Supabase dispute resolve notice:", resolveError);
      restoreTask(task);
      throw new Error("GigPay couldn't save the resolution, so the task is still frozen. Try again in a moment.");
    }

    addToast("Dispute resolved! Escrow workflow resumed to In Progress.", "success");
  };

  // 8. Update Task Status with Permanent Milestone Completion & Dynamic Public Ledger Registration
  const updateTaskStatus = async (id, newStatus, assignFreelancer = false) => {
    const taskToUpdate = tasks.find(t => t.id === id || t.title === id);
    if (!taskToUpdate) return;
    
    if (newStatus === 'Completed' && isDisputeActive(taskToUpdate)) {
      throw new Error("Cannot release funds while task is in Disputed status. Dispute must be resolved first.");
    }

    // Accepting needs the Freelancer role in the database (RLS); confirm it before claiming the task.
    if (assignFreelancer && typeof ensureDbRole === 'function' && !(await ensureDbRole('freelancer'))) {
      throw new Error("GigPay couldn't confirm your Freelancer role. Sign out, sign back in, then accept again.");
    }

    const activeKey = publicKey || 'GBDEMO_GIGPAY_WALLET_FALLBACK_ACTIVE_V9XQ3P';
    const snapshot = { ...taskToUpdate };
    const updatedFields = {
      status: newStatus
    };

    if (assignFreelancer && user) {
      updatedFields.freelancer_id = user.id;
    }

    // Optimistic Update: instantly update UI & broadcast across all open tabs/windows
    updateTasksAndCache((prev) => prev.map((t) => (t.id === id || t.title === id) ? { ...t, ...updatedFields } : t));

    // The contract reports this escrow as already paid out (an earlier, slow release went through):
    // record it as Completed without sending a second release or inventing a release hash.
    const markAlreadyReleased = async (onChainTask) => {
      const done = { status: 'Completed', completed_at: new Date().toISOString() };
      restoreTask({
        ...snapshot,
        ...done,
        // Fill in the escrow's own wallets from the chain only where this copy lacks them (write-once fields).
        client_wallet: snapshot.client_wallet || onChainTask?.client || null,
        freelancer_wallet: snapshot.freelancer_wallet || onChainTask?.freelancer || null
      });
      await writeTask(snapshot.id, done);
      addToast("Stellar shows this payment was already released to the freelancer, so no new payment was sent. The task is now marked Completed.", "info");
      return { success: true, alreadyReleased: true };
    };

    let releaseResult = null;
    try {
      if (newStatus === 'Completed') {
        releaseResult = await submitApproveTask({
          clientAddress: taskToUpdate.client_wallet || activeKey,
          taskId: taskToUpdate
        });
        if (releaseResult?.alreadyReleased) {
          return await markAlreadyReleased(releaseResult.onChainTask);
        }

        const relHash = releaseResult?.hash || ('rel-' + Date.now().toString(16));
        const releaseIsEvidence = !releaseResult?.isDemo && !isNonEvidenceHash(relHash);
        updatedFields.release_tx_hash = relHash;
        updatedFields.completed_at = new Date().toISOString();

        // Record the wallets the escrow actually used (not the viewer's key or a default address),
        // and only when the release is a confirmed on-chain transaction.
        if (releaseIsEvidence) {
          addLedgerRecord(labelLedgerRecord({
            id: 'tx-rel-' + Date.now(),
            taskId: taskToUpdate.title,
            method: 'approve_task',
            amount: `${taskToUpdate.amount} XLM`,
            contractId: GIGPAY_ESCROW_CONTRACT_ID,
            clientWallet: taskToUpdate.client_wallet || null,
            freelancerWallet: taskToUpdate.freelancer_wallet || null,
            txHash: relHash,
            status: 'Completed & Released',
            timestamp: new Date().toISOString().replace('T', ' ').substring(0, 19) + ' UTC',
            explorerUrl: releaseResult?.explorerUrl || `https://stellar.expert/explorer/testnet/tx/${relHash}`
          }));
        }
      } else {
        await requestWalletSignature(activeKey, `Action: Task ${String(id).slice(0, 8)}`);
      }
    } catch (signErr) {
      // Fallback for when the contract's "already approved" text does reach the app.
      if (newStatus === 'Completed' && /already released/i.test(signErr?.message || '')) {
        return await markAlreadyReleased(null);
      }
      restoreTask(snapshot);
      throw signErr;
    }

    const saveError = await writeTask(snapshot.id, updatedFields);
    if (saveError) {
      console.warn("Supabase update notice:", saveError);
      if (newStatus === 'Completed') {
        // The money already moved on-chain, so keep Completed (the chain is the truth); only the shared
        // record is behind. A later fetch can't demote it.
        addToast("Payment released on Stellar, but GigPay couldn't update the shared record yet. Refresh in a minute; please don't release again.", "warning");
      } else {
        restoreTask(snapshot);
        throw new Error(assignFreelancer
          ? "Someone else may have accepted this task first, or it pays a different freelancer. Refresh to see the latest tasks."
          : "GigPay couldn't save this change. Refresh and try again.");
      }
    }

    if (releaseResult?.explorerUrl && !releaseResult?.isDemo) {
      addToast(`Escrow released on Testnet! Tx: ${releaseResult.hash.slice(0, 10)}...`, "success");
    }

    return releaseResult || { success: true };
  };

  const approveMilestone = async (taskId) => {
    const targetId = (taskId && typeof taskId === 'object') ? taskId.id : taskId;
    if (!targetId) throw new Error("Invalid milestone identifier provided.");
    return await updateTaskStatus(targetId, 'Completed');
  };

  const handleReleaseFunds = approveMilestone;

  // 9. Unified Dynamic Public Verification Ledger:
  // Dynamically aggregates completed milestones from tasks + manually recorded transactions + all 10 SOW Table 7 records
  const ledgerRecords = useMemo(() => {
    // Evidence rules (see src/lib/ledgerIntegrity.js): only confirmed on-chain hashes, the wallets
    // the escrow actually used (never a placeholder or another tester's wallet), one row per tx hash,
    // and every row labeled outside-user vs team/test wallet.

    // 1. Completed tasks that carry a confirmed release hash
    const completedRows = tasks
      .filter(t => t.status === 'Completed' || t.status === 'Paid')
      .map(rawT => {
        const t = sanitizeTaskRecord(rawT);
        return buildCompletedTaskLedgerRow(t, VERIFIED_TASK_ONCHAIN_MAP[t.id]);
      })
      .filter(Boolean);

    // 2. Live records written by addTask / updateTaskStatus, and 3. baseline SOW Table 7 records
    const liveRows = storedLedgerRecords.map(labelLedgerRecord);
    const baselineRows = INITIAL_VERIFICATION_LEDGER.map(labelLedgerRecord);

    return dedupeLedgerByTxHash([...completedRows, ...liveRows, ...baselineRows]);
  }, [tasks, storedLedgerRecords]);

  // 10. 1-Click CSV Export for Public Verification Ledger
  const exportVerificationCsv = () => {
    try {
      const headers = ["Transaction ID", "Task Title", "Method", "Amount", "Contract ID", "Client Wallet", "Freelancer Wallet", "Transaction Hash", "Status", "Timestamp (UTC)", "Stellar Expert URL", "Counts As Outside User", "Wallet Note"];
      const rows = ledgerRecords.map(r => [
        `"${r.id}"`,
        `"${r.taskId || ''}"`,
        `"${r.method || ''}"`,
        `"${r.amount || ''}"`,
        `"${r.contractId || ''}"`,
        `"${r.clientWallet || ''}"`,
        `"${r.freelancerWallet || ''}"`,
        `"${r.txHash || ''}"`,
        `"${r.status || ''}"`,
        `"${r.timestamp || ''}"`,
        `"${r.explorerUrl || ''}"`,
        `"${r.countsAsOutsideUser ? 'Yes' : 'No'}"`,
        `"${r.walletNote || ''}"`
      ]);

      const csvString = [headers.join(","), ...rows.map(e => e.join(","))].join("\n");
      const blob = new Blob([csvString], { type: "text/csv;charset=utf-8;" });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.setAttribute("href", url);
      link.setAttribute("download", `gigpay_onchain_verification_ledger_${Date.now()}.csv`);
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
      addToast("Verification Ledger exported to CSV successfully!", "success");
    } catch (err) {
      console.error("CSV Export failed:", err);
      addToast("Failed to export verification ledger.", "error");
    }
  };

  return (
    <TaskContext.Provider value={{ 
      tasks, 
      isLoading, 
      addTask, 
      updateTaskStatus, 
      approveMilestone,
      handleReleaseFunds,
      submitProofOfWork, 
      raiseDispute, 
      resolveDispute,
      ledgerRecords,
      exportVerificationCsv
    }}>
      {children}
    </TaskContext.Provider>
  );
};
